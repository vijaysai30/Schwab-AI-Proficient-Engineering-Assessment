CREATE TABLE IF NOT EXISTS learner (
    id VARCHAR(64) PRIMARY KEY
);

CREATE TABLE IF NOT EXISTS learner_completion (
    learner_id VARCHAR(64) NOT NULL,
    course_id VARCHAR(64) NOT NULL,
    PRIMARY KEY (learner_id, course_id),
    FOREIGN KEY (learner_id) REFERENCES learner (id)
);

CREATE TABLE IF NOT EXISTS course_offering (
    id VARCHAR(64) PRIMARY KEY,
    capacity INT NOT NULL CHECK (capacity >= 0)
);

CREATE TABLE IF NOT EXISTS offering_prerequisite (
    offering_id VARCHAR(64) NOT NULL,
    course_id VARCHAR(64) NOT NULL,
    PRIMARY KEY (offering_id, course_id),
    FOREIGN KEY (offering_id) REFERENCES course_offering (id)
);

CREATE TABLE IF NOT EXISTS enrollment (
    offering_id VARCHAR(64) NOT NULL,
    learner_id VARCHAR(64) NOT NULL,
    position_seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
    PRIMARY KEY (offering_id, learner_id),
    FOREIGN KEY (offering_id) REFERENCES course_offering (id),
    FOREIGN KEY (learner_id) REFERENCES learner (id)
);

CREATE TABLE IF NOT EXISTS waitlist_entry (
    offering_id VARCHAR(64) NOT NULL,
    learner_id VARCHAR(64) NOT NULL,
    sequence_no BIGINT NOT NULL,
    PRIMARY KEY (offering_id, learner_id),
    UNIQUE (offering_id, sequence_no),
    FOREIGN KEY (offering_id) REFERENCES course_offering (id),
    FOREIGN KEY (learner_id) REFERENCES learner (id)
);

CREATE TABLE IF NOT EXISTS waitlist_sequence (
    offering_id VARCHAR(64) PRIMARY KEY,
    next_value BIGINT NOT NULL,
    FOREIGN KEY (offering_id) REFERENCES course_offering (id)
);
